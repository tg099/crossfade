"""YouTube uploads as sources: video titles must still find the plain song (seen live with the
Google-code login, where only video titles and channel names come back)."""
import pytest

from crossfade import matcher, versions
from crossfade.identity import search_queries
from crossfade.models import Track
from crossfade.providers import ytm as ytm_mod
from crossfade.providers.ytm import YTMProvider, _topic_meta

OMV, UGC, ATV = "MUSIC_VIDEO_TYPE_OMV", "MUSIC_VIDEO_TYPE_UGC", "MUSIC_VIDEO_TYPE_ATV"


@pytest.mark.parametrize("title", ["Noch da (Official Version)", "Dracula (Official Video)", "Am I Dreaming (Visualizer)",
                                   "Superhelden (VISUALIZER)", "déjà vu 1997 (prod. by reezy)", "Sucker [Official Visualizer]",
                                   "Big Dawgs | Prod. Kalmi (Official Music Video)", "Habits (Lyrics)"])
def test_upload_words_are_not_a_version(title):
    assert versions.version_of(title).label() == "Original"


def test_real_versions_survive_noise_stripping():
    assert "Remix" in versions.version_of("Habits (Hippie Sabotage Remix) (Official Video)").hard
    assert "Live" in versions.version_of("Numb (Live) [Official Video]").hard


@pytest.mark.parametrize("title,channel,vt,want", [
    ("Cro - Noch da (Official Version)", "Chimperator Channel", None, ("Noch da (Official Version)", "Cro")),
    ("TOM HENGST - STONEY (Official Video)", "Tom Hengst", OMV, ("STONEY (Official Video)", "Tom Hengst")),
    ("The Emptiness Machine (Official Music Video) - Linkin Park", "Linkin Park", None,
     ("The Emptiness Machine (Official Music Video)", "Linkin Park")),
    ("DARDAN x NIMO ~ PARA DRILL", "Hypnotize Entertainment", None, ("PARA DRILL", "DARDAN x NIMO")),
    ("Song - Remastered 2011", "Queen", ATV, ("Song - Remastered 2011", "Queen")),
])
def test_tidy_video(title, channel, vt, want):
    assert matcher.tidy_video(title, channel, vt) == want


def test_music_video_matches_song_despite_longer_runtime():
    src = Track("ytm", "v", "Noch da (Official Version)", "Cro", duration=231, video_type=OMV)
    cand = Track("apple", "1", "noch da", "CRO", album="tru.", duration=192)
    a = matcher.assess(src, cand)
    assert a.score >= matcher.ACCEPT and a.exact


def test_fan_upload_title_artist_order_is_tried_both_ways():
    src = Track("ytm", "v", "Sweater Weather - The Neighbourhood (Lyrics)", "Aura Melodies", duration=240, video_type=UGC)
    cand = Track("apple", "1", "Sweater Weather", "The Neighbourhood", duration=240)
    assert matcher.assess(src, cand).score >= matcher.ACCEPT
    texts = [q for k, q in search_queries(src) if k != "isrc"]
    assert any(q.lower().startswith("sweater weather") for q in texts)


def test_audio_tracks_keep_one_reading():
    t = Track("apple", "1", "Song - Live", "X")
    assert matcher.readings(t) == [t]


def test_topic_description():
    desc = ("Provided to YouTube by Universal Music Group\n\nnoch da · CRO\n\ntru. (Deluxe Edition)\n\n"
            "℗ 2025 Chimperator\n\nReleased on: 2025-05-02\n\nAuto-generated by YouTube.")
    assert _topic_meta(desc, "noch da", "CRO") == ("noch da", "CRO", "tru. (Deluxe Edition)")
    assert _topic_meta("random text", "t", "a") == ("t", "a", "")


def test_enrich_uses_ytm_song_details_once(monkeypatch):
    calls = []

    class FakeYT:
        def get_watch_playlist(self, vid, limit=1):
            calls.append(vid)
            return {"tracks": [{"videoId": vid, "title": "PIZZA SALAMI", "videoType": OMV,
                                "artists": [{"name": "LX"}, {"name": "Bonez MC"}]}]}

    monkeypatch.setattr(ytm_mod, "YTMusic", FakeYT)
    p = YTMProvider.__new__(YTMProvider)
    p.meta_store = ytm_mod.MemoryMetaStore()
    t = Track("ytm", "abc", "LX & Bonez - PIZZA SALAMI (DeeVoe)", "CrhymeTV")
    p._enrich([t])
    assert (t.title, t.artist, t.video_type) == ("PIZZA SALAMI", "LX, Bonez MC", OMV)
    t2 = Track("ytm", "abc", "LX & Bonez - PIZZA SALAMI (DeeVoe)", "CrhymeTV")
    p._enrich([t2])
    assert calls == ["abc"] and t2.title == "PIZZA SALAMI"


def test_remixer_named_in_title_is_not_taken_for_the_artist():
    assert matcher.tidy_video("belis - EAST COAST BABY (MRJay Remix)", "MRJay", OMV) == \
        ("EAST COAST BABY (MRJay Remix)", "belis")


def test_other_artist_is_never_exact():
    src = Track("ytm", "v", "STONEY (Official Video)", "Tom Hengst", duration=143, video_type=OMV)
    a = matcher.assess(src, Track("apple", "1", "Stoney", "SANITO", duration=140))
    assert not a.exact and a.score < matcher.ACCEPT


def test_artist_catalog_finds_what_search_misses(tmp_path):
    """Seen live: 'stoney Tom Hengst' -> no search hit, but the artist page lists 'Stoney'."""
    from crossfade.db import Database
    from crossfade.identity import Identity

    class Prov:
        browsed = []

        def search(self, q, limit=10):
            return [Track("apple", "1", "Stoney", "SANITO", duration=140)]

        def by_isrc(self, i):
            return []

        def artist_tracks(self, artist):
            self.browsed.append(artist)
            return [Track("apple", "2", "Nix zu Nix", "Tom Hengst"), Track("apple", "3", "Stoney", "Tom Hengst", album="Zwei Zimmer")]

    ident = Identity(Database(tmp_path / "t.db"))
    src = Track("ytm", "v", "STONEY (Official Video)", "Tom Hengst", duration=143, video_type=OMV)
    p = Prov()
    m = ident.find(ident.song_for(src), "apple", p, source=src)
    assert m.track.id == "3" and m.accepted("closest") and p.browsed == ["Tom Hengst"]


def test_queries_use_remixer_and_drop_emoji():
    src = Track(service="ytm", id="v1", title="EAST COAST BABY (MRJay Remix)", artist="belis", album="",
                duration=209, video_type="MUSIC_VIDEO_TYPE_OMV")
    texts = [q for k, q in search_queries(src) if k != "isrc"]
    assert "east coast baby MRJay" in texts
    src = Track(service="ytm", id="v2", title="WMNB🍻🥨", artist="Bonez MC, RAF Camora, Gzuz", album="",
                duration=229, video_type="MUSIC_VIDEO_TYPE_OMV")
    assert all("🍻" not in q for _, q in search_queries(src))
